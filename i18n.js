    root = root || document;
    var nl = root.querySelectorAll('[data-i18n]'), i;
    for (i = 0; i < nl.length; i++) nl[i].textContent = t(nl[i].getAttribute('data-i18n'));
    nl = root.querySelectorAll('[data-i18n-ph]');
    for (i = 0; i < nl.length; i++) nl[i].setAttribute('placeholder', t(nl[i].getAttribute('data-i18n-ph')));
    nl = root.querySelectorAll('[data-i18n-title]');
    for (i = 0; i < nl.length; i++) nl[i].setAttribute('title', t(nl[i].getAttribute('data-i18n-title')));
    nl = root.querySelectorAll('[data-i18n-html]');
    for (i = 0; i < nl.length; i++) nl[i].innerHTML = t(nl[i].getAttribute('data-i18n-html'));
    document.documentElement.setAttribute('lang', LANG === 'en' ? 'en' : 'zh-CN');
