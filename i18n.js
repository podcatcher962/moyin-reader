  var ZH = {};

  var LANG = 'zh';

  function t(s, a) {
    var out = s;
    if (LANG === 'en') {
      if (EN[s] !== undefined) out = EN[s];
    } else if (ZH[s] !== undefined) out = ZH[s];
    if (a && typeof out === 'string' && out.indexOf('{') >= 0) {
      out = out.replace(/\{(\w+)\}/g, function (m, k) {
        return a[k] !== undefined ? a[k] : m;
      });
    }
    return out;
  }

  /* 静态界面：把 data-i18n / -ph / -title / -html 的元素刷一遍 */
